"""Protocol types for Luna core interfaces."""
from __future__ import annotations

from collections.abc import AsyncIterator, Awaitable, Callable
from dataclasses import dataclass
from typing import Any, Protocol, runtime_checkable

from core.providers.base import (
    StreamEvent,
    ToolCall,
)


@runtime_checkable
class ToolHandler(Protocol):
    """Protocol for tool handler functions."""
    def __call__(self, **kwargs: Any) -> Awaitable[str]: ...


@runtime_checkable
class ToolRegistryProtocol(Protocol):
    """Protocol for tool registry."""
    def get(self, name: str) -> Any: ...
    @property
    def definitions(self) -> list[dict]: ...
    def set_permissions(self, evaluator: Any) -> None: ...
    def execute(self, call: ToolCall) -> Awaitable[str]: ...
    def register(self, tool: Any) -> None: ...
    def set_blocked(self, names: set[str]) -> None: ...
    def undo_last(self) -> list[str]: ...
    def redo_last(self) -> list[str]: ...


@runtime_checkable
class AgentCoreProtocol(Protocol):
    """Protocol for AgentCore."""
    router: Any
    tools: ToolRegistryProtocol
    config: Any
    messages: list[dict]

    def run(self, user_input: str) -> AsyncIterator[StreamEvent | str]: ...
    def _build_messages(self) -> list[dict]: ...
    def set_system_prompt(self, prompt: str) -> None: ...
    async def set_provider(self, provider: str | None = None, model: str | None = None) -> None: ...
    def set_emma_context(self, context: str) -> None: ...
    def set_mode(self, mode: Any) -> None: ...
    def reset(self) -> None: ...
    def load_messages(self, messages: list[dict]) -> None: ...
    def undo_last(self) -> list[str]: ...
    def redo_last(self) -> list[str]: ...


@runtime_checkable
class AIProviderProtocol(Protocol):
    """Protocol for AI providers."""
    @property
    def name(self) -> str: ...
    @property
    def default_model(self) -> str: ...
    @property
    def base_url(self) -> str: ...
    @property
    def api_key(self) -> str: ...

    async def complete(
        self,
        messages: list[dict],
        tools: list[dict] | None = None,
    ) -> AsyncIterator[StreamEvent]: ...

    async def list_models(self) -> list[str]: ...
    async def switch_model(self, model: str) -> None: ...
    async def test_connection(self) -> tuple[bool, str]: ...


@runtime_checkable
class SessionManagerProtocol(Protocol):
    """Protocol for session management."""
    session_dir: Any
    _current: str | None

    async def list_sessions(self) -> list[dict]: ...
    async def save(self, messages: list[dict], debounce: bool = True) -> str: ...
    def mark_dirty(self) -> None: ...
    async def flush(self, messages: list[dict]) -> str: ...
    async def load(self, session_id: str) -> dict | None: ...
    def new(self) -> None: ...
    async def delete(self, session_id: str) -> bool: ...


@runtime_checkable
class ConfigManagerProtocol(Protocol):
    """Protocol for configuration management."""
    env: Any
    config_path: Any
    config: Any

    @property
    def active_agent(self) -> str: ...
    @active_agent.setter
    def active_agent(self, name: str) -> None: ...

    def get_agent(self, name: str) -> Any | None: ...
    def get_all_agents(self) -> dict[str, Any]: ...
    def set_agent(self, name: str, config: Any) -> None: ...
    def remove_agent(self, name: str) -> bool: ...

    def get_model_for_agent(self, agent_name: str) -> str | None: ...
    def get_agent_permissions(self, agent_name: str) -> dict[str, str]: ...
    def list_agents(self) -> list[dict]: ...

    def save(self) -> None: ...


@runtime_checkable
class SkillManagerProtocol(Protocol):
    """Protocol for skill management."""
    def get(self, name: str) -> Any | None: ...
    def list_skills(self) -> list[Any]: ...
    def match(self, query: str) -> list[Any]: ...
    def load_skills(self) -> list[str]: ...
    def get_active(self) -> set[str]: ...
    def activate(self, name: str) -> bool: ...
    def deactivate(self, name: str) -> bool: ...
    def get_system_prompt_additions(self) -> str: ...


@runtime_checkable
class SubagentManagerProtocol(Protocol):
    """Protocol for subagent management."""
    def get(self, name: str) -> Any | None: ...
    def list_subagents(self) -> list[Any]: ...
    def match(self, query: str) -> list[Any]: ...
    def task_description(self) -> str: ...
    async def run(self, name: str, prompt: str, model_overrides: dict[str, str] | None = None) -> str: ...


@runtime_checkable
class ReferenceManagerProtocol(Protocol):
    """Protocol for reference management."""
    def get(self, name: str) -> Any | None: ...
    def list(self) -> list[str]: ...
    def discover(self, path: Any) -> None: ...
    def read(self, name: str, query: str) -> str: ...
    def add(self, name: str, path: str) -> bool: ...
    def remove(self, name: str) -> bool: ...


@runtime_checkable
class RouterProtocol(Protocol):
    """Protocol for AI router."""
    settings: Any
    provider_manager: Any

    @property
    def active_name(self) -> str: ...

    async def get_provider(self, name: str | None = None) -> AIProviderProtocol: ...
    async def set_active(self, name: str) -> None: ...
    async def reconfigure(self, name: str, **kwargs) -> None: ...
    async def cached_models(self, name: str | None = None) -> list[str]: ...
    def cached_models_sync(self, name: str | None = None) -> list[str]: ...
    def provider_names_sync(self) -> list[str]: ...
    async def cycle_model(self) -> str: ...
    @property
    def active_model(self) -> str: ...
    async def list_providers(self) -> list[dict]: ...
    async def list_models(self, name: str) -> list[str]: ...
    async def test_connection(self, name: str) -> tuple[bool, str]: ...
    async def provider_info(self, name: str) -> str: ...
    async def switch_model(self, name: str | None = None, model: str | None = None) -> None: ...


@runtime_checkable
class ToolExecutorProtocol(Protocol):
    """Protocol for tool executor."""
    tools: ToolRegistryProtocol
    permissions: Any

    async def execute(self, tool_call: ToolCall) -> str: ...
    def undo_last(self) -> list[str]: ...
    def redo_last(self) -> list[str]: ...
    def get_history(self) -> list[dict]: ...


@dataclass
class ProviderConfig:
    """Provider configuration."""
    type: str
    api_key: str = ""
    base_url: str = ""
    model: str = ""
    label: str = ""


# Type aliases for common patterns
Message = dict[str, Any]
Messages = list[Message]
ToolCalls = list[ToolCall]
ToolCallResults = list[dict[str, Any]]

# Callback types
ProviderGetter = Callable[[], Awaitable[AIProviderProtocol]]
ProviderNameGetter = Callable[[], str]
LSPDiagnosticsCallback = Callable[[], Awaitable[None]]
FormatCallback = Callable[[str], str]
